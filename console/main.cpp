/* ---- icon cache ---- */

struct IconCacheEntry {
  char id[16];
  unsigned char* data;
  std::size_t length;
  unsigned long long used;
};

IconCacheEntry g_icons[kIconSlots];
std::size_t g_icon_bytes = 0;
unsigned long long g_icon_tick = 0;
pthread_mutex_t g_icon_lock = PTHREAD_MUTEX_INITIALIZER;

/** Caller must hold g_icon_lock. A free slot first, otherwise the oldest. */
int icon_slot_to_replace() {
  int pick = -1;
  for (int i = 0; i < kIconSlots; i++) {
    if (!g_icons[i].data) return i;
    if (pick < 0 || g_icons[i].used < g_icons[pick].used) pick = i;
  }
  return pick;
}

/** Caller must hold g_icon_lock. */
void icon_forget(int slot) {
  if (!g_icons[slot].data) return;
  g_icon_bytes -= g_icons[slot].length;
  std::free(g_icons[slot].data);
  g_icons[slot].data = nullptr;
  g_icons[slot].length = 0;
  g_icons[slot].id[0] = '\0';
}

/** A rescan can change which file a title's icon comes from. */
void icon_clear() {
  pthread_mutex_lock(&g_icon_lock);
  for (int i = 0; i < kIconSlots; i++) icon_forget(i);
  g_icon_bytes = 0;
  pthread_mutex_unlock(&g_icon_lock);
}

/**
 * Hands back a copy of a title's icon, reading flash only the first time. The
 * copy belongs to the caller: a slow client must not hold up every other tile
 * behind the cache lock.
 */
bool icon_take(const char* id, unsigned char** out, std::size_t* out_length) {
  *out = nullptr;
  *out_length = 0;

  pthread_mutex_lock(&g_icon_lock);
  for (int i = 0; i < kIconSlots; i++) {
    if (!g_icons[i].data || std::strcmp(g_icons[i].id, id) != 0) continue;
    unsigned char* copy = static_cast<unsigned char*>(std::malloc(g_icons[i].length));
    if (copy) {
      std::memcpy(copy, g_icons[i].data, g_icons[i].length);
      *out = copy;
      *out_length = g_icons[i].length;
      g_icons[i].used = ++g_icon_tick;
    }
    pthread_mutex_unlock(&g_icon_lock);
    return *out != nullptr;
  }
  pthread_mutex_unlock(&g_icon_lock);

  char icon_path[640] = {0};
  pthread_mutex_lock(&g_lock);
  const int index = find_title_locked(id);
  if (index >= 0 && g_titles[index].hasIcon) {
    std::snprintf(icon_path, sizeof icon_path, "%s/sce_sys/icon0.png", g_titles[index].path);
  }
  pthread_mutex_unlock(&g_lock);
  if (!icon_path[0]) return false;

  // O_NOFOLLOW: a dump's icon is a plain file. A symlink standing in for one
  // must not be able to hand out another file on the console.
  const int file = ::open(icon_path, O_RDONLY | O_NOFOLLOW);
  if (file < 0) return false;
  struct stat info;
  if (::fstat(file, &info) != 0 || info.st_size <= 0 ||
      static_cast<unsigned long long>(info.st_size) > static_cast<unsigned long long>(kIconMaxBytes)) {
    ::close(file);
    log_fmt("icon: skipping %s (missing or larger than the cache allows)", icon_path);
    return false;
  }

  const std::size_t size = static_cast<std::size_t>(info.st_size);
  unsigned char* buffer = static_cast<unsigned char*>(std::malloc(size));
  if (!buffer) {
    ::close(file);
    return false;
  }
  std::size_t used = 0;
  while (used < size) {
    const ssize_t got = ::read(file, buffer + used, size - used);
    if (got <= 0) break;
    used += static_cast<std::size_t>(got);
  }
  ::close(file);
  if (used != size) {
    std::free(buffer);
    return false;
  }

  pthread_mutex_lock(&g_icon_lock);
  while (g_icon_bytes + used > kIconMaxBytes) {
    const int slot = icon_slot_to_replace();
    if (slot < 0 || !g_icons[slot].data) break;
    icon_forget(slot);
  }
  const int slot = icon_slot_to_replace();
  if (slot >= 0) {
    icon_forget(slot);
    g_icons[slot].data = static_cast<unsigned char*>(std::malloc(used));
    if (g_icons[slot].data) {
      std::memcpy(g_icons[slot].data, buffer, used);
      g_icons[slot].length = used;
      g_icon_bytes += used;
      std::snprintf(g_icons[slot].id, sizeof g_icons[slot].id, "%s", id);
      g_icons[slot].used = ++g_icon_tick;
    }
  }
  pthread_mutex_unlock(&g_icon_lock);

  *out = buffer;
  *out_length = used;
  return true;
}

