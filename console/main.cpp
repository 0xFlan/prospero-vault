/**
 * Serialises the title list.
 *
 * Caller must hold g_lock.
 *
 * Each entry is composed on its own and copied in only if it fits. Adding
 * snprintf's return value straight to the offset — which is what this did —
 * counts the characters a *truncated* call would have written, so once the
 * offset passes the end, `cap - n` wraps to a huge value and the next call
 * writes outside the buffer. A library near the cap with long, escape-heavy
 * title names reaches that, and a title name comes from a dump's own metadata.
 *
 * The array is closed whatever happens: the interface never receives half a
 * document, and the list is cut on a whole entry rather than mid-title.
 */
void games_json(char* out, std::size_t cap) {
  if (cap < 64) {
    if (cap) out[0] = '\0';
    return;
  }

  const int head = std::snprintf(out, cap,
                                 "{\"mac\":\"%s\",\"scanning\":%s,\"playing\":%s,\"games\":[", g_mac,
                                 g_scanning ? "true" : "false", g_playing ? "true" : "false");
  if (head <= 0 || static_cast<std::size_t>(head) >= cap - 4) {
    std::snprintf(out, cap, "{\"mac\":\"\",\"scanning\":false,\"playing\":false,\"games\":[]}");
    return;
  }

  std::size_t n = static_cast<std::size_t>(head);
  bool first = true;
  bool cut = false;

  for (int i = 0; i < g_count; i++) {
    char name[256];
    jescape(name, sizeof name, g_titles[i].name);
    // A package is installed and mounted by the console itself. Only an image
    // leans on a mount payload, so only an image can be unplayable right now.
    const bool is_pkg = std::strcmp(g_titles[i].kind, "pkg") == 0;
    const bool is_image = std::strcmp(g_titles[i].kind, "image") == 0;
    const bool is_app = std::strcmp(g_titles[i].kind, "app") == 0;
    const bool native = is_pkg || is_app || (is_image && g_mount_payload == 1);

    char entry[640];
    const int length = std::snprintf(
        entry, sizeof entry,
        "{\"id\":\"%s\",\"name\":\"%s\",\"kind\":\"%s\",\"platform\":\"%s\",\"size\":%lld,"
        "\"icon\":%s,\"pkg\":%s,\"installed\":%s,\"native\":%s}",
        g_titles[i].id, name, g_titles[i].kind, g_titles[i].platform, g_titles[i].size,
        g_titles[i].hasIcon ? "true" : "false", is_pkg ? "true" : "false",
        g_titles[i].installed ? "true" : "false", native ? "true" : "false");
    if (length <= 0 || static_cast<std::size_t>(length) >= sizeof entry) continue;

    const std::size_t size = static_cast<std::size_t>(length);
    // Four bytes stay back for "]}", so the closer always has room.
    if (n + size + (first ? 0 : 1) + 4 > cap) {
      cut = true;
      break;
    }
    if (!first) out[n++] = ',';
    std::memcpy(out + n, entry, size);
    n += size;
    first = false;
  }

  std::memcpy(out + n, "]}", 3);
  if (cut) log_fmt("games: the body limit cut the list short of %d titles", g_count);
}

unsigned long long fnv1a(const char* data, std::size_t length) {
  unsigned long long hash = 1469598103934665603ull;
  for (std::size_t i = 0; i < length; i++) {
    hash ^= static_cast<unsigned char>(data[i]);
    hash *= 1099511628211ull;
  }
  return hash;
}

/** Caller must hold g_lock. Keeps the serialised body and its tag in step. */
void rebuild_json_locked() {
  games_json(g_json, sizeof g_json);
  g_json_len = std::strlen(g_json);
  g_json_tag = fnv1a(g_json, g_json_len);
}

