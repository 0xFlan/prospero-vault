void load_config() {
  const int fd = ::open(kConfigFile, O_RDONLY);
  if (fd < 0) return;
  char buffer[512] = {0};
  const ssize_t bytes = ::read(fd, buffer, sizeof buffer - 1);
  ::close(fd);
  if (bytes <= 0) return;

  char* at = std::strstr(buffer, "\"mac\"");
  if (!at) return;
  at = std::strchr(at, ':');
  if (!at) return;
  at = std::strchr(at, '"');
  if (!at) return;
  at++;
  std::size_t i = 0;
  while (*at && *at != '"' && i + 1 < sizeof g_mac) g_mac[i++] = *at++;
  g_mac[i] = '\0';
}

void save_config() {
  char mac[96];
  pthread_mutex_lock(&g_lock);
  std::snprintf(mac, sizeof mac, "%s", g_mac);
  pthread_mutex_unlock(&g_lock);

  char buffer[256];
  std::snprintf(buffer, sizeof buffer, "{\n  \"mac\": \"%s\"\n}\n", mac);

  // Write beside the file and rename over it: a power cut during a truncating
  // write would otherwise leave config.json empty and lose the Mac's address.
  char temp[320];
  std::snprintf(temp, sizeof temp, "%s.tmp", kConfigFile);
  const int fd = ::open(temp, O_WRONLY | O_CREAT | O_TRUNC, 0666);
  if (fd < 0) return;
  const bool wrote = write_all(fd, buffer, std::strlen(buffer));
  ::fsync(fd);
  ::close(fd);
  if (wrote) ::rename(temp, kConfigFile);
}

