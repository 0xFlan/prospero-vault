/**
 * Whether the console already holds this title as an installed app. One call,
 * so a tile can say "Installed" honestly instead of offering an install that
 * has already happened.
 */
bool title_installed(const char* id) {
#if PV_HAVE_SONY
  if (!id || !id[0]) return false;
  // The shell creates this directory only after an install is complete, so it
  // is the same answer AppInstUtil gave without loading that library.
  char path[256];
  std::snprintf(path, sizeof path, "%s/%s", PV_APP_ROOT, id);
  struct stat info;
  if (::stat(path, &info) == 0 && S_ISDIR(info.st_mode)) return true;
  std::snprintf(path, sizeof path, "/user/appmeta/%s", id);
  return ::stat(path, &info) == 0;
#else
  (void)id;
  return false;
#endif
}

void add_title(const char* id, const char* name, const char* path, const char* kind, const char* platform,
               long long size, bool icon, bool installed) {
  if (g_scan_count >= kMaxTitles) return;
  for (int i = 0; i < g_scan_count; i++) {
    if (std::strcmp(g_scan[i].id, id) != 0) continue;
    // A package is the smallest playable copy, and an image is mountable where a
    // dump is not, so both win over a folder of the same title.
    // An installed app is the most startable form there is, so it wins; a
    // package beats a dump, and an image beats a dump.
    const bool replaces = std::strcmp(kind, "app") == 0 || std::strcmp(kind, "pkg") == 0 ||
                          (std::strcmp(kind, "image") == 0 && std::strcmp(g_scan[i].kind, "dump") == 0);
    if (!replaces) return;
    Title& existing = g_scan[i];
    std::snprintf(existing.name, sizeof existing.name, "%s", name);
    std::snprintf(existing.path, sizeof existing.path, "%s", path);
    std::snprintf(existing.kind, sizeof existing.kind, "%s", kind);
    std::snprintf(existing.platform, sizeof existing.platform, "%s", platform);
    existing.size = size;
    existing.hasIcon = icon;
    existing.installed = installed;
    return;
  }
  Title& entry = g_scan[g_scan_count++];
  std::snprintf(entry.id, sizeof entry.id, "%s", id);
  std::snprintf(entry.name, sizeof entry.name, "%s", name);
  std::snprintf(entry.path, sizeof entry.path, "%s", path);
  std::snprintf(entry.kind, sizeof entry.kind, "%s", kind);
  std::snprintf(entry.platform, sizeof entry.platform, "%s", platform);
  entry.size = size;
  entry.hasIcon = icon;
  entry.installed = installed;
}

/** Reads a small metadata file whole. The scan owns this buffer, under g_scan_lock. */
bool read_small_file(const char* path, char* out, std::size_t cap) {
  const int fd = ::open(path, O_RDONLY);
  if (fd < 0) return false;
  const ssize_t bytes = ::read(fd, out, cap - 1);
  ::close(fd);
  if (bytes <= 0) return false;
  out[bytes] = '\0';
  return true;
}

void scan_dir(const char* root, int depth) {
  // Our own app folder is a title too, and it is not part of the library.
  if (std::strcmp(root, kHomeAppDir) == 0) return;

  DIR* dir = ::opendir(root);
  if (!dir) return;

  struct dirent* entry = nullptr;
  while ((entry = ::readdir(dir)) != nullptr) {
    if (entry->d_name[0] == '.') continue;

    char full[512];
    std::snprintf(full, sizeof full, "%s/%s", root, entry->d_name);

    // stat() on every entry was the scan's main cost on a full drive. The
    // directory entry already says what it is, and only a package or an image
    // needs a size, so ordinary files are skipped without touching flash.
    struct stat info;
    bool is_dir = entry->d_type == DT_DIR;
    bool is_file = entry->d_type == DT_REG;
    if (entry->d_type == DT_UNKNOWN && ::stat(full, &info) == 0) {
      is_dir = S_ISDIR(info.st_mode);
      is_file = S_ISREG(info.st_mode);
    }
    if (!is_dir && !is_file) continue;  // links, sockets, devices

    if (is_dir) {
      // A dump is recognised by the metadata inside it, not by its folder name.
      // DLC lives in content-id folders, and many dumps are named after the
      // game; both were invisible while only title-id folders counted.
      bool has_metadata = false;
      if (!is_title_id(entry->d_name)) {
        char probe[640];
        std::snprintf(probe, sizeof probe, "%s/sce_sys/param.json", full);
        has_metadata = ::access(probe, F_OK) == 0;
        if (!has_metadata) {
          std::snprintf(probe, sizeof probe, "%s/sce_sys/param.sfo", full);
          has_metadata = ::access(probe, F_OK) == 0;
        }
      }

      if (is_title_id(entry->d_name) || has_metadata) {
        char json_path[640];
        char sfo_path[640];
        std::snprintf(json_path, sizeof json_path, "%s/sce_sys/param.json", full);
        std::snprintf(sfo_path, sizeof sfo_path, "%s/sce_sys/param.sfo", full);

        char title[96] = {0};
        char id[16] = {0};
        const char* platform = "?";
        static char metadata[65536];

        // A PS5 dump ships param.json; a PS4 dump ships param.sfo. Reading only
        // the SFO hid every PS5 dump from the library.
        if (read_small_file(json_path, metadata, sizeof metadata)) {
          platform = "PS5";
          json_string(metadata, "titleId", id, sizeof id);
          json_string(metadata, "titleName", title, sizeof title);
        } else if (::access(sfo_path, F_OK) == 0) {
          platform = "PS4";
          sfo_read(sfo_path, title, sizeof title, id, sizeof id);
        } else {
          if (depth < 2) scan_dir(full, depth + 1);
          continue;
        }

        // A folder that is not a title id gets a stable short id, so two
        // differently-named dumps cannot collide on a truncated folder name.
        if (!id[0] && is_title_id(entry->d_name)) std::snprintf(id, sizeof id, "%s", entry->d_name);
        if (!id[0]) source_id(full, id, sizeof id);
        if (!title[0]) std::snprintf(title, sizeof title, "%s", entry->d_name);

        char icon[640];
        std::snprintf(icon, sizeof icon, "%s/sce_sys/icon0.png", full);

        add_title(id, title, full, "dump", platform, 0, ::access(icon, F_OK) == 0, false);
        log_fmt("scan: dump %s %s (%s)", id, full, platform);
        continue;
      }
      if (depth < 2) scan_dir(full, depth + 1);
      continue;
    }

    const bool is_pkg = ends_with(entry->d_name, ".pkg");
    if (!is_pkg && !is_image_file(entry->d_name)) continue;
    if (entry->d_type != DT_UNKNOWN && (::stat(full, &info) != 0 || !S_ISREG(info.st_mode))) continue;

    if (is_pkg) {
      char stem[64];
      std::snprintf(stem, sizeof stem, "%s", entry->d_name);
      const std::size_t length = std::strlen(stem);
      if (length > 4) stem[length - 4] = '\0';
      char id[16] = {0};
      package_title_id(stem, id, sizeof id);
      if (!id[0]) std::snprintf(id, sizeof id, "%s", stem);
      add_title(id, entry->d_name, full, "pkg", "PS5", info.st_size, false, title_installed(id));
      log_fmt("scan: pkg %s (%s)", full, id);
      continue;
    }

    {
      // No filesystem to read until it is mounted, so the name has to do.
      char stem[64];
      std::snprintf(stem, sizeof stem, "%s", entry->d_name);
      char* dot = std::strrchr(stem, '.');
      if (dot) *dot = '\0';
      add_title(stem, entry->d_name, full, "image", "PS5", info.st_size, false, false);
      log_fmt("scan: image %s", full);
    }
  }

  ::closedir(dir);
}

/**
 * Titles the console already holds as installed apps.
 *
 * This is what makes an existing FPKG playable in one tap even when the .pkg
 * file is long gone: the shell has the app under PV_APP_ROOT and its own
 * launcher can start it as it is. Nothing is mounted, copied or rebuilt. If the
 * directory is not readable by this payload the walk is simply empty.
 */
/**
 * Additional content lives under /user/addcont, one folder per content id.
 * Every DLC of a game shares the base title id, so keying by title id would
 * collapse a season pass into a single tile — the content id folder is what
 * makes each piece separate. Without this walk the library never showed DLC.
 */
void scan_addcont() {
  DIR* root = ::opendir("/user/addcont");
  if (!root) return;

  struct dirent* title = nullptr;
  while ((title = ::readdir(root)) != nullptr) {
    if (title->d_name[0] == '.' || title->d_type != DT_DIR) continue;

    char base[512];
    std::snprintf(base, sizeof base, "/user/addcont/%s", title->d_name);

    static char metadata[65536];
    DIR* inner = ::opendir(base);
    if (!inner) continue;

    bool found = false;
    struct dirent* content = nullptr;
    while ((content = ::readdir(inner)) != nullptr) {
      if (content->d_name[0] == '.' || content->d_type != DT_DIR) continue;

      char dir[640];
      std::snprintf(dir, sizeof dir, "%s/%s", base, content->d_name);

      char json_path[700];
      char sfo_path[700];
      std::snprintf(json_path, sizeof json_path, "%s/sce_sys/param.json", dir);
      std::snprintf(sfo_path, sizeof sfo_path, "%s/sce_sys/param.sfo", dir);
      if (::access(json_path, F_OK) != 0 && ::access(sfo_path, F_OK) != 0) continue;

      char name[96] = {0};
      char ignored[16] = {0};
      const char* platform = "PS5";
      if (read_small_file(json_path, metadata, sizeof metadata)) {
        json_string(metadata, "titleName", name, sizeof name);
        if (!name[0]) json_string(metadata, "title", name, sizeof name);
      } else {
        platform = "PS4";
        sfo_read(sfo_path, name, sizeof name, ignored, sizeof ignored);
      }
      if (!name[0]) std::snprintf(name, sizeof name, "%s", content->d_name);

      char tile[16];
      source_id(content->d_name, tile, sizeof tile);
      char icon[700];
      std::snprintf(icon, sizeof icon, "%s/sce_sys/icon0.png", dir);
      add_title(tile, name, dir, "dump", platform, 0, ::access(icon, F_OK) == 0, false);
      log_fmt("scan: additional content %s %s", tile, dir);
      found = true;
    }
    ::closedir(inner);

    // Some contents sit directly under the title id instead of a content id.
    if (!found) {
      char json_path[700];
      std::snprintf(json_path, sizeof json_path, "%s/sce_sys/param.json", base);
      if (::access(json_path, F_OK) == 0) {
        char name[96] = {0};
        if (read_small_file(json_path, metadata, sizeof metadata)) {
          json_string(metadata, "titleName", name, sizeof name);
          if (!name[0]) json_string(metadata, "title", name, sizeof name);
        }
        if (!name[0]) std::snprintf(name, sizeof name, "%s", title->d_name);
        char tile[16];
        source_id(title->d_name, tile, sizeof tile);
        add_title(tile, name, base, "dump", "PS5", 0, false, false);
        log_fmt("scan: additional content %s %s", tile, base);
      }
    }
  }
  ::closedir(root);
}

void scan_installed() {
  DIR* dir = ::opendir(PV_APP_ROOT);
  if (!dir) return;

  struct dirent* entry = nullptr;
  while ((entry = ::readdir(dir)) != nullptr) {
    if (entry->d_name[0] == '.' || !is_title_id(entry->d_name)) continue;

    char full[512];
    std::snprintf(full, sizeof full, "%s/%s", PV_APP_ROOT, entry->d_name);

    char json_path[640];
    char sfo_path[640];
    std::snprintf(json_path, sizeof json_path, "%s/sce_sys/param.json", full);
    std::snprintf(sfo_path, sizeof sfo_path, "%s/sce_sys/param.sfo", full);

    char title[96] = {0};
    char id[16] = {0};
    const char* platform = "PS5";
    static char metadata[65536];

    if (read_small_file(json_path, metadata, sizeof metadata)) {
      json_string(metadata, "titleId", id, sizeof id);
      json_string(metadata, "titleName", title, sizeof title);
    } else if (::access(sfo_path, F_OK) == 0) {
      platform = "PS4";
      sfo_read(sfo_path, title, sizeof title, id, sizeof id);
    }
    // Without metadata the title id is still enough to start it.
    if (!title[0]) std::snprintf(title, sizeof title, "%s", entry->d_name);

    char icon[640];
    std::snprintf(icon, sizeof icon, "%s/sce_sys/icon0.png", full);
    add_title(entry->d_name, title, full, "app", platform, 0, ::access(icon, F_OK) == 0, true);
  }
  ::closedir(dir);
  log_fmt("scan: installed apps read from %s", PV_APP_ROOT);
}

/** Case-insensitive by title, then by id: the grid is always in one order. */
int title_order(const void* left, const void* right) {
  const Title* a = static_cast<const Title*>(left);
  const Title* b = static_cast<const Title*>(right);
  const int by_name = ::strcasecmp(a->name, b->name);
  return by_name != 0 ? by_name : ::strcasecmp(a->id, b->id);
}

/** Walks every mount into the scratch array, then swaps it in under g_lock. */
void scan_all() {
  pthread_mutex_lock(&g_scan_lock);

  pthread_mutex_lock(&g_lock);
  g_scanning = true;
  rebuild_json_locked();
  pthread_mutex_unlock(&g_lock);

  // Ask again with every walk: whether an image can be mounted right now is
  // part of what the list has to say, and a payload started later is noticed.
  mount_payload_ready(true);

  g_scan_count = 0;
  static const char* roots[] = {
      kGames,
      "/data/homebrew",
      "/user/data",
      "/mnt/usb0", "/mnt/usb1", "/mnt/usb2", "/mnt/usb3",
      "/mnt/usb4", "/mnt/usb5", "/mnt/usb6", "/mnt/usb7",
  };
  for (const char* root : roots) scan_dir(root, 0);
  scan_addcont();
  // Last, so a real package or dump tile is never replaced by a lesser one.
  scan_installed();

  if (g_scan_count > 1) {
    std::qsort(g_scan, static_cast<std::size_t>(g_scan_count), sizeof(Title), title_order);
  }

  pthread_mutex_lock(&g_lock);
  std::memcpy(g_titles, g_scan, sizeof(Title) * static_cast<std::size_t>(g_scan_count));
  g_count = g_scan_count;
  g_scanning = false;
  // Serialise once here: the interface polls this body every few seconds.
  rebuild_json_locked();
  const int found = g_count;
  pthread_mutex_unlock(&g_lock);
  pthread_mutex_unlock(&g_scan_lock);
  icon_clear();
  log_fmt("scan: %d titles", found);
}

/** The scan cannot hold the listener: the page has to load while it runs. */
void* scan_thread(void*) {
  scan_all();
  return nullptr;
}

/**
 * A partial download resumes from its size, so it is worth keeping across a
 * reboot — deleting every .part at startup threw away bytes that a retry would
 * have reused. Only one nobody came back for in a week is removed.
 */
constexpr long long kPartialKeepSeconds = 7 * 24 * 60 * 60;

void sweep_partials() {
  DIR* dir = ::opendir(kGames);
  if (!dir) return;
  const std::time_t now = std::time(nullptr);
  struct dirent* entry = nullptr;
  while ((entry = ::readdir(dir)) != nullptr) {
    if (entry->d_name[0] == '.') continue;
    if (!ends_with(entry->d_name, ".part")) continue;
    char full[640];
    std::snprintf(full, sizeof full, "%s/%s", kGames, entry->d_name);

    struct stat info;
    if (::stat(full, &info) == 0 && now - info.st_mtime < kPartialKeepSeconds) {
      log_fmt("cleanup: keeping resumable %s", full);
      continue;
    }
    if (::unlink(full) == 0) log_fmt("cleanup: removed %s", full);
  }
  ::closedir(dir);
}

