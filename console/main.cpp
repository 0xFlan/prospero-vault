/** The on-console engine is a separate payload; 8095 is its fixed port. */
constexpr const char* kPackSession = "http://127.0.0.1:8095/api/session";
constexpr const char* kPackStart = "http://127.0.0.1:8095/api/start_job";

bool pack_engine(char* version, std::size_t cap) {
  if (version && cap) version[0] = '\0';
  char body[1024] = {0};
  if (http_call("GET", kPackSession, nullptr, body, sizeof body) != 200) return false;
  if (version && cap) json_string(body, "version", version, cap);
  return true;
}

/** Chooses a package name that is not on disk; the engine refuses an existing output. */
bool pack_output_path(const char* id, char* out, std::size_t cap) {
  for (int n = 1; n <= 99; n++) {
    if (n == 1) {
      std::snprintf(out, cap, "%s/%s-console.pkg", kGames, id);
    } else {
      std::snprintf(out, cap, "%s/%s-console-%d.pkg", kGames, id, n);
    }
    if (::access(out, F_OK) != 0) return true;
  }
  return false;
}

bool pack_start(const char* id, char* message, std::size_t cap) {
  char source[512] = {0};
  char kind[12] = {0};
  long long source_size = 0;

  pthread_mutex_lock(&g_lock);
  const int index = find_title_locked(id);
  if (index >= 0) {
    std::snprintf(source, sizeof source, "%s", g_titles[index].path);
    std::snprintf(kind, sizeof kind, "%s", g_titles[index].kind);
    source_size = g_titles[index].size;
  }
  // A dump and an installed app can share an id; the scan keeps one tile, so
  // the folder has to be found from the dump roots, not from the merged entry.
  const bool found_dump = dump_source_locked(id, source, sizeof source, &source_size);
  if (found_dump) std::snprintf(kind, sizeof kind, "dump");
  const bool busy = g_pack.active;
  pthread_mutex_unlock(&g_lock);

  // A folder tile carries no size. Walk it once, outside the lock, so the
  // progress bar means something on a 60 GB dump and the UI stays responsive.
  if (source[0] && source_size <= 0) source_size = folder_bytes(source, 0);

  if (busy) {
    std::snprintf(message, cap, "A console pack is already running. Wait for it to finish.");
    return false;
  }
  if (!source[0]) {
    std::snprintf(message, cap, "%s is no longer in the library. Rescan, then try again.", id);
    return false;
  }
  if (std::strcmp(kind, "dump") != 0) {
    std::snprintf(message, cap,
                  "Only a dump is packed here. A package is already packed, and an image is "
                  "mounted as it is.");
    return false;
  }

  char output[512] = {0};
  if (!pack_output_path(id, output, sizeof output)) {
    std::snprintf(message, cap, "There are already too many console packages for %s. Delete one first.", id);
    return false;
  }

  char safe_source[700];
  char safe_output[700];
  jescape(safe_source, sizeof safe_source, source);
  jescape(safe_output, sizeof safe_output, output);
  char request[1800];
  std::snprintf(request, sizeof request,
                "{\"request\":{\"source\":\"%s\",\"format\":\"pkg\",\"output\":\"%s\","
                "\"kraken_level\":\"fast\"}}",
                safe_source, safe_output);

  char answer[1024] = {0};
  const int status = http_call("POST", kPackStart, request, answer, sizeof answer);
  if (status != 200) {
    char why[320] = {0};
    if (!json_string(answer, "error", why, sizeof why)) {
      std::snprintf(why, sizeof why, "The on-console packer refused the job (HTTP %d).", status);
    }
    std::snprintf(message, cap, "%s", why);
    return false;
  }

  const int job = std::atoi(answer);
  if (job <= 0) {
    std::snprintf(message, cap, "The on-console packer accepted the job but returned no id.");
    return false;
  }

  const auto now = std::chrono::steady_clock::now().time_since_epoch();
  pthread_mutex_lock(&g_lock);
  g_pack.active = true;
  g_pack.done = false;
  g_pack.ok = false;
  g_pack.engine_job = job;
  std::snprintf(g_pack.id, sizeof g_pack.id, "%s", id);
  std::snprintf(g_pack.output, sizeof g_pack.output, "%s", output);
  g_pack.source_size = source_size;
  g_pack.started_ms = std::chrono::duration_cast<std::chrono::milliseconds>(now).count();
  std::snprintf(g_pack.message, sizeof g_pack.message, "Packing on the console…");
  pthread_mutex_unlock(&g_lock);

  std::snprintf(message, cap, "Packing %s on the console. This can take a while.", id);
  return true;
}

/** Builds the status body. The output appearing is the success signal: the engine renames a verified .part. */
void pack_status_json(char* out, std::size_t cap) {
  PackJob snapshot;
  pthread_mutex_lock(&g_lock);
  snapshot = g_pack;
  pthread_mutex_unlock(&g_lock);

  bool active = snapshot.active;
  bool done = snapshot.done;
  bool ok = snapshot.ok;
  int pct = 0;
  char message[320];
  std::snprintf(message, sizeof message, "%s", snapshot.message);

  struct stat info;
  const bool landed = snapshot.output[0] && ::stat(snapshot.output, &info) == 0 &&
                      S_ISREG(info.st_mode) && info.st_size > 0;
  if (landed) {
    active = false;
    done = true;
    ok = true;
    pct = 100;
    std::snprintf(message, sizeof message, "Package ready: %s", snapshot.output);
    pthread_mutex_lock(&g_lock);
    g_pack.active = false;
    g_pack.done = true;
    g_pack.ok = true;
    std::snprintf(g_pack.message, sizeof g_pack.message, "%s", message);
    pthread_mutex_unlock(&g_lock);
  } else if (active) {
    // The engine writes <output>.<pid>-<n>.part and renames it when verified.
    // Sum those parts: a rough percentage beats a spinner that never moves.
    long long part = 0;
    const char* base = std::strrchr(snapshot.output, '/');
    base = base ? base + 1 : snapshot.output;
    DIR* dir = ::opendir(kGames);
    if (dir) {
      struct dirent* entry;
      while ((entry = ::readdir(dir)) != nullptr) {
        if (std::strncmp(entry->d_name, base, std::strlen(base)) != 0) continue;
        if (std::strstr(entry->d_name, ".part") == nullptr) continue;
        char path[640];
        std::snprintf(path, sizeof path, "%s/%s", kGames, entry->d_name);
        struct stat part_info;
        if (::stat(path, &part_info) == 0 && S_ISREG(part_info.st_mode)) part += part_info.st_size;
      }
      ::closedir(dir);
    }
    if (part > 0) {
      pct = snapshot.source_size > 0
                ? static_cast<int>((part * 100) / snapshot.source_size)
                : 1;
      if (pct > 95) pct = 95;
      std::snprintf(message, sizeof message, "Packing on the console — %lld MB written",
                    part / (1024 * 1024));
    } else {
      pct = 1;
      std::snprintf(message, sizeof message, "Waiting for the on-console packer…");
    }
  } else if (!done) {
    message[0] = '\0';
    std::snprintf(message, sizeof message, "No console pack is running.");
  }

  char safe_message[420];
  char safe_output[700];
  char safe_id[32];
  jescape(safe_message, sizeof safe_message, message);
  jescape(safe_output, sizeof safe_output, snapshot.output);
  jescape(safe_id, sizeof safe_id, snapshot.id);
  std::snprintf(out, cap,
                "{\"ok\":true,\"active\":%s,\"done\":%s,\"ok\":%s,\"pct\":%d,"
                "\"kind\":\"pack\",\"id\":\"%s\",\"message\":\"%s\",\"output\":\"%s\"}",
                active ? "true" : "false", done ? "true" : "false", ok ? "true" : "false", pct,
                safe_id, safe_message, safe_output);
}

/**
 * Streams a URL to a file. Returns 0 on success.
 *
 * Content-Length is treated as a promise: a short read means the transfer was
 * cut off. Half a package must never be renamed into place as if it were whole.
 * A .part file left by an earlier attempt is continued with a Range request, so
 * a dropped link costs the bytes lost rather than the whole package.
 */
int download_once(const char* url, const char* dest, long long known_total, long long* out_bytes, char* why,
                  std::size_t why_cap, bool may_restart) {
  *out_bytes = 0;

  Target target;
  if (!parse_http_url(url, &target)) {
    std::snprintf(why, why_cap, "Only plain http:// URLs are accepted");
    return -1;
  }

  struct stat existing;
  long long offset = 0;
  if (::stat(dest, &existing) == 0 && S_ISREG(existing.st_mode) && existing.st_size > 0) {
    offset = static_cast<long long>(existing.st_size);
  }
  // A partial that already fills the package is not partial, and one longer
  // than the package belongs to an older copy of it.
  if (offset > 0 && known_total > 0 && offset >= known_total) {
    log_fmt("download: discarding a stale partial for %s", dest);
    ::unlink(dest);
    offset = 0;
  }
  if (offset > 0) log_fmt("download: resuming %s at %lld bytes", dest, offset);

  const int fd = connect_to(target.host, target.port);
  if (fd < 0) {
    std::snprintf(why, why_cap, "Cannot reach %.32s:%.8s", target.host, target.port);
    return -2;
  }
  set_timeouts(fd, 30, 30);

  char request[1024];
  const int request_length = offset > 0
      ? std::snprintf(request, sizeof request,
                      "GET %s HTTP/1.0\r\nHost: %s:%s\r\nUser-Agent: prospero-vault/%s\r\n"
                      "Accept: */*\r\nRange: bytes=%lld-\r\nConnection: close\r\n\r\n",
                      target.path, target.host, target.port, kVersion, offset)
      : std::snprintf(request, sizeof request,
                      "GET %s HTTP/1.0\r\nHost: %s:%s\r\nUser-Agent: prospero-vault/%s\r\n"
                      "Accept: */*\r\nConnection: close\r\n\r\n",
                      target.path, target.host, target.port, kVersion);
  if (request_length <= 0) {
    ::close(fd);
    return -3;
  }
  write_all(fd, request, static_cast<std::size_t>(request_length));

  char buffer[8192];
  std::size_t used = 0;
  char* body_start = nullptr;
  std::size_t body_used = 0;

  while (used < sizeof buffer - 1) {
    const ssize_t got = ::recv(fd, buffer + used, sizeof buffer - 1 - used, 0);
    if (got <= 0) break;
    used += static_cast<std::size_t>(got);
    buffer[used] = '\0';
    char* marker = std::strstr(buffer, "\r\n\r\n");
    if (marker) {
      body_start = marker + 4;
      body_used = used - static_cast<std::size_t>(body_start - buffer);
      break;
    }
  }

  if (!body_start) {
    ::close(fd);
    std::snprintf(why, why_cap, "Host sent no header");
    return -4;
  }

  const bool resumed = std::strstr(buffer, " 206 ") != nullptr;
  if (!resumed && std::strstr(buffer, " 200 ") == nullptr) {
    ::close(fd);
    std::snprintf(why, why_cap, "Host answered %.24s", buffer);
    return -5;
  }

  // A host that ignores Range resends the whole file, so start from zero again.
  const long long start = resumed && offset > 0 ? offset : 0;
  long long expected = -1;
  const char* length_at = std::strstr(buffer, "Content-Length:");
  if (!length_at) length_at = std::strstr(buffer, "content-length:");
  if (length_at) {
    expected = start + std::atoll(length_at + std::strlen("Content-Length:"));
  } else if (known_total > 0) {
    expected = known_total;
  }

  // The host and the ready check disagree about the size: the .part is stale.
  if (may_restart && start > 0 && known_total > 0 && expected > 0 && expected != known_total) {
    ::close(fd);
    ::unlink(dest);
    log_fmt("download: %s changed size, starting over", dest);
    return download_once(url, dest, known_total, out_bytes, why, why_cap, false);
  }

  const int out = ::open(dest, O_WRONLY | O_CREAT | (start > 0 ? O_APPEND : O_TRUNC), 0666);
  if (out < 0) {
    ::close(fd);
    std::snprintf(why, why_cap, "Cannot write %s", dest);
    return -6;
  }

  long long total = start;
  int result = 0;
  int last_pct = -1;
  if (body_used) {
    if (!write_all(out, body_start, body_used)) {
      std::snprintf(why, why_cap, "Storage is full or read-only");
      result = -12;
    } else {
      total += static_cast<long long>(body_used);
    }
  }
  while (result == 0) {
    if (cancel_requested()) {
      std::snprintf(why, why_cap, "Cancelled");
      result = -10;
      break;
    }
    const ssize_t got = ::recv(fd, buffer, sizeof buffer, 0);
    if (got == 0) break;
    if (got < 0) {
      if (errno == EINTR) continue;
      std::snprintf(why, why_cap, "Read error after %lld bytes", total);
      result = -7;
      break;
    }
    // A short write would otherwise count bytes that never reached the disk.
    if (!write_all(out, buffer, static_cast<std::size_t>(got))) {
      std::snprintf(why, why_cap, "Storage is full or read-only");
      result = -12;
      break;
    }
    total += got;
    // The declared length ends the message; a keep-alive host may never close.
    if (expected > 0 && total >= expected) break;
    if (total > kMaxPackageBytes) {
      std::snprintf(why, why_cap, "Package exceeds the size cap");
      result = -8;
      break;
    }

    // A multi-gigabyte pull needs a moving bar, not a flat 96%.
    if (expected > 0) {
      const int pct = 96 + static_cast<int>((total * 3) / expected);
      if (pct != last_pct) {
        last_pct = pct;
        char have[32];
        char want[32];
        human_size(have, sizeof have, total);
        human_size(want, sizeof want, expected);
        char line[112];
        std::snprintf(line, sizeof line, "receiving package · %s / %s", have, want);
        job_set(line, pct > 99 ? 99 : pct);
      }
    } else if (total / (16LL * 1024 * 1024) != (total - got) / (16LL * 1024 * 1024)) {
      char have[32];
      human_size(have, sizeof have, total);
      char line[96];
      std::snprintf(line, sizeof line, "receiving package · %s", have);
      job_set(line, 97);
    }
  }
  // Every byte has to be durable before the rename can publish the file.
  if (result == 0 && ::fsync(out) != 0) log_fmt("download: fsync of %s failed", dest);
  ::close(out);
  ::close(fd);
  if (result == 0 && total == 0) {
    std::snprintf(why, why_cap, "Empty body");
    result = -9;
  }
  if (result == 0 && expected > 0 && total != expected) {
    std::snprintf(why, why_cap, "Transfer stopped at %lld of %lld bytes", total, expected);
    result = -11;
  }
  *out_bytes = total;
  return result;
}

int download(const char* url, const char* dest, long long known_total, long long* out_bytes, char* why,
             std::size_t why_cap) {
  return download_once(url, dest, known_total, out_bytes, why, why_cap, true);
}

