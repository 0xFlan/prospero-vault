// Prospero Vault — console payload.
//
// Serves its own interface on port 8097. Open http://127.0.0.1:8097 in the
// console browser (or that address from any device on the LAN).
//
// What it does here, on the console:
//   - scans /data, /user/data and the USB mounts for PS5 dumps (sce_sys/
//     param.json), PS4 dumps (sce_sys/param.sfo), FPKGs and mounted image
//     formats (.exfat, .ffpkg, .ffpfs, .ffpfsc)
//   - starts serving before the scan finishes, so the page appears at once and
//     fills in as titles are found
//   - serves a thumbnail grid, one icon per title
//   - "Convert" asks the Mac to package a dump, then pulls the finished .pkg
//     onto this console. Packing cannot happen here: there is no FPKG packer
//     for the console, only desktop engines.
//   - conversion runs on a worker thread so the interface stays responsive and
//     can poll /api/convert/status for the progress bar
//   - "Play" starts a title through Sony's own launcher (sceLncUtilLaunchApp /
//     sceSystemServiceLaunchApp), asking a running ShadowMountPlus to mount and
//     set the fake-library policy first when it is present. No title cache is
//     built or kept, so playing costs no extra disk and no rebuild step.
//
// Status: cross-compiles against the PS5 payload SDK and runs on a console;
// the launch path has not yet been exercised on hardware.

