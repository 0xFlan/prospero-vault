void reply_bytes(int fd, int status, const char* type, const void* body, std::size_t length) {
    const char* reason = status == 200 ? "OK" : status == 202 ? "Accepted" : status == 204 ? "No Content"
                        : status == 304 ? "Not Modified"
                        : status == 400 ? "Bad Request" : status == 404 ? "Not Found"
                        : status == 409 ? "Conflict" : status == 422 ? "Unprocessable Entity"
                        : status == 500 ? "Internal Server Error"
                        : status == 501 ? "Not Implemented" : status == 502 ? "Bad Gateway" : "Error";
  char header[320];
  const int header_length = std::snprintf(
      header, sizeof header,
      "HTTP/1.1 %d %s\r\nContent-Type: %s\r\nContent-Length: %zu\r\n"
      "Cache-Control: no-store\r\nConnection: close\r\n\r\n",
      status, reason, type, length);
  if (header_length > 0) write_all(fd, header, static_cast<std::size_t>(header_length));
  if (length) write_all(fd, body, length);
}

void reply(int fd, int status, const char* body) {
  reply_bytes(fd, status, "application/json", body, std::strlen(body));
}

/**
 * Reads a string field out of a JSON body.
 *
 * Escapes are decoded. Sony metadata is ordinary JSON, so a title such as
 * `Ratchet \"Rift\" Apart` arrives escaped; copying bytes up to the first bare
 * quote stopped at the escape and left the backslash in the name, which then
 * showed in the library with a stray `\` and lost everything after the quote.
 */
bool json_string(const char* body, const char* key, char* out, std::size_t cap) {
  char pattern[64];
  std::snprintf(pattern, sizeof pattern, "\"%s\"", key);
  const char* at = std::strstr(body, pattern);
  if (!at) return false;
  at += std::strlen(pattern);
  while (*at && *at != ':') at++;
  if (*at != ':') return false;
  at++;
  while (*at == ' ' || *at == '\t') at++;
  if (*at != '"') return false;
  at++;

  std::size_t i = 0;
  while (*at && i + 1 < cap) {
    if (*at == '"') break;
    if (*at != '\\' || !at[1]) {
      out[i++] = *at++;
      continue;
    }

    const char next = at[1];
    if (next == 'n' || next == 'r' || next == 't' || next == 'b' || next == 'f') {
      // A name is drawn on one line, so a control escape becomes a space.
      out[i++] = ' ';
      at += 2;
      continue;
    }
    if (next == 'u') {
      unsigned code = 0;
      bool digits = true;
      for (int k = 2; k < 6 && digits; k++) {
        const char c = at[k];
        const int value = c >= '0' && c <= '9'   ? c - '0'
                          : c >= 'a' && c <= 'f' ? c - 'a' + 10
                          : c >= 'A' && c <= 'F' ? c - 'A' + 10
                                                 : -1;
        if (value < 0) {
          digits = false;
        } else {
          code = code * 16 + static_cast<unsigned>(value);
        }
      }
      if (digits) {
        // UTF-8, so the name reads the same as it did in the JSON. A lone
        // surrogate cannot be represented without its pair; it becomes '?'.
        if (code < 0x80) {
          out[i++] = static_cast<char>(code);
        } else if (code < 0x800) {
          if (i + 2 >= cap) break;
          out[i++] = static_cast<char>(0xC0 | (code >> 6));
          out[i++] = static_cast<char>(0x80 | (code & 0x3F));
        } else if (code >= 0xD800 && code <= 0xDFFF) {
          out[i++] = '?';
        } else {
          if (i + 3 >= cap) break;
          out[i++] = static_cast<char>(0xE0 | (code >> 12));
          out[i++] = static_cast<char>(0x80 | ((code >> 6) & 0x3F));
          out[i++] = static_cast<char>(0x80 | (code & 0x3F));
        }
        at += 6;
        continue;
      }
    }

    // \" \\ \/ and anything this does not recognise: the escaped character.
    out[i++] = next;
    at += 2;
  }
  out[i] = '\0';
  return i > 0;
}

int json_int(const char* body, const char* key, int fallback) {
  char pattern[64];
  std::snprintf(pattern, sizeof pattern, "\"%s\"", key);
  const char* at = std::strstr(body, pattern);
  if (!at) return fallback;
  at = std::strchr(at, ':');
  if (!at) return fallback;
  return std::atoi(at + 1);
}

void url_encode(char* out, std::size_t cap, const char* text) {
  static const char* hex = "0123456789ABCDEF";
  std::size_t n = 0;
  for (const unsigned char* p = reinterpret_cast<const unsigned char*>(text); *p && n + 4 < cap; p++) {
    const unsigned char c = *p;
    if ((c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9') ||
        c == '-' || c == '_' || c == '.' || c == '~') {
      out[n++] = static_cast<char>(c);
    } else {
      out[n++] = '%';
      out[n++] = hex[c >> 4];
      out[n++] = hex[c & 0x0F];
    }
  }
  out[n] = '\0';
}

void jescape(char* out, std::size_t cap, const char* text) {
  std::size_t n = 0;
  for (const char* p = text; *p && n + 2 < cap; p++) {
    if (*p == '"' || *p == '\\') {
      out[n++] = '\\';
      out[n++] = *p;
    } else if (static_cast<unsigned char>(*p) < 0x20) {
      out[n++] = ' ';
    } else {
      out[n++] = *p;
    }
  }
  out[n] = '\0';
}

struct Target {
  char host[128];
  char port[8];
  char path[512];
};

bool parse_http_url(const char* url, Target* out) {
  const char* prefix = "http://";
  if (std::strncmp(url, prefix, std::strlen(prefix)) != 0) return false;
  const char* rest = url + std::strlen(prefix);
  const char* slash = std::strchr(rest, '/');
  if (!slash) return false;

  const std::size_t host_length = static_cast<std::size_t>(slash - rest);
  if (host_length == 0 || host_length >= sizeof out->host) return false;

  char authority[160];
  std::memcpy(authority, rest, host_length);
  authority[host_length] = '\0';

  char* colon = std::strchr(authority, ':');
  if (colon) {
    *colon = '\0';
    std::snprintf(out->port, sizeof out->port, "%s", colon + 1);
  } else {
    std::snprintf(out->port, sizeof out->port, "80");
  }
  std::snprintf(out->host, sizeof out->host, "%s", authority);
  std::snprintf(out->path, sizeof out->path, "%s", slash);
  return out->host[0] != '\0';
}

int connect_to(const char* host, const char* port) {
  struct addrinfo hints;
  std::memset(&hints, 0, sizeof hints);
  hints.ai_family = AF_INET;
  hints.ai_socktype = SOCK_STREAM;

  struct addrinfo* found = nullptr;
  if (::getaddrinfo(host, port, &hints, &found) != 0 || !found) return -1;

  const int fd = ::socket(found->ai_family, found->ai_socktype, found->ai_protocol);
  if (fd < 0) {
    ::freeaddrinfo(found);
    return -1;
  }
  const int flags = ::fcntl(fd, F_GETFL, 0);
  if (flags >= 0) ::fcntl(fd, F_SETFL, flags | O_NONBLOCK);

  int result = ::connect(fd, found->ai_addr, found->ai_addrlen);
  ::freeaddrinfo(found);

  // A connect to a switched-off Mac can hang for over a minute. Six seconds is
  // long enough for a sleeping Wi-Fi link and short enough to fail while the
  // progress bar still means something.
  if (result != 0 && errno == EINPROGRESS) {
    fd_set ready;
    FD_ZERO(&ready);
    FD_SET(fd, &ready);
    struct timeval limit;
    limit.tv_sec = 6;
    limit.tv_usec = 0;
    result = ::select(fd + 1, nullptr, &ready, nullptr, &limit) > 0 ? 0 : -1;
    if (result == 0) {
      int failure = 0;
      socklen_t length = sizeof failure;
      if (::getsockopt(fd, SOL_SOCKET, SO_ERROR, &failure, &length) != 0 || failure != 0) result = -1;
    }
  } else if (result != 0) {
    result = -1;
  }

  if (flags >= 0) ::fcntl(fd, F_SETFL, flags);
  if (result != 0) {
    ::close(fd);
    return -1;
  }
  return fd;
}

/** Plain HTTP call with an explicit content type. Returns the status code, or a negative value on failure. */
int http_call_ex(const char* method, const char* url, const char* body, const char* content_type,
                 char* response, std::size_t cap) {
  Target target;
  if (!parse_http_url(url, &target)) return -1;

  const int fd = connect_to(target.host, target.port);
  if (fd < 0) return -2;
  set_timeouts(fd, 20, 20);

  char request[1024];
  const int length = body
      ? std::snprintf(request, sizeof request,
                      "%s %s HTTP/1.0\r\nHost: %s:%s\r\nUser-Agent: prospero-vault/%s\r\n"
                      "Content-Type: %s\r\nContent-Length: %zu\r\n"
                      "Connection: close\r\n\r\n%s",
                      method, target.path, target.host, target.port, kVersion, content_type,
                      std::strlen(body), body)
      : std::snprintf(request, sizeof request,
                      "%s %s HTTP/1.0\r\nHost: %s:%s\r\nUser-Agent: prospero-vault/%s\r\n"
                      "Connection: close\r\n\r\n",
                      method, target.path, target.host, target.port, kVersion);
  if (length <= 0) {
    ::close(fd);
    return -3;
  }
  write_all(fd, request, static_cast<std::size_t>(length));

  // Per call, never static: the play path and a conversion can be talking to
  // two hosts at the same moment, and a shared buffer would splice the answers.
  char buffer[16384];
  std::size_t used = 0;
  std::size_t body_at = 0;
  bool header_done = false;
  long long body_expected = -1;
  while (used < sizeof buffer - 1) {
    const ssize_t got = ::recv(fd, buffer + used, sizeof buffer - 1 - used, 0);
    if (got <= 0) break;
    used += static_cast<std::size_t>(got);
    buffer[used] = '\0';

    if (!header_done) {
      const char* marker = std::strstr(buffer, "\r\n\r\n");
      if (marker) {
        header_done = true;
        body_at = static_cast<std::size_t>(marker + 4 - buffer);
        const char* length_at = std::strstr(buffer, "Content-Length:");
        if (!length_at) length_at = std::strstr(buffer, "content-length:");
        if (length_at) {
          body_expected = std::atoll(length_at + 15);
        } else {
          // No length: only a chunked answer needs reading to the end.
          const bool chunked = std::strstr(buffer, "Transfer-Encoding:") != nullptr ||
                               std::strstr(buffer, "transfer-encoding:") != nullptr;
          body_expected = chunked ? -1 : 0;
        }
      }
    }

    // Content-Length is the end of this message. Waiting for the peer to close
    // instead deadlocks against a host that keeps the connection alive — which
    // is exactly what stalled every conversion at "asking your Mac to pack".
    if (header_done && body_expected >= 0 &&
        static_cast<long long>(used - body_at) >= body_expected) {
      break;
    }
  }
  buffer[used] = '\0';
  ::close(fd);

  int status = -4;
  if (std::strncmp(buffer, "HTTP/", 5) == 0) {
    const char* space = std::strchr(buffer, ' ');
    if (space) status = std::atoi(space + 1);
  }

  if (response && cap) {
    const char* marker = std::strstr(buffer, "\r\n\r\n");
    std::snprintf(response, cap, "%s", marker ? marker + 4 : "");
  }
  return status;
}

/** JSON is the default; form posts go through the explicit variant above. */
int http_call(const char* method, const char* url, const char* body, char* response, std::size_t cap) {
  return http_call_ex(method, url, body, "application/json", response, cap);
}

