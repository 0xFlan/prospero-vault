void run_convert(const char* id) {
  char mac[96];
  pthread_mutex_lock(&g_lock);
  std::snprintf(mac, sizeof mac, "%s", g_mac);
  pthread_mutex_unlock(&g_lock);

  if (!mac[0]) {
    job_finish(false, "Set your Mac's address first, in Settings.");
    return;
  }
  if (cancel_requested()) {
    job_finish(false, "Cancelled");
    return;
  }

  // Refuse a folder that no packer could turn into a package, before spending
  // an hour transferring it.
  {
    char source[512] = {0};
    char source_kind[12] = {0};
    pthread_mutex_lock(&g_lock);
    const int index = find_title_locked(id);
    if (index >= 0) {
      std::snprintf(source, sizeof source, "%s", g_titles[index].path);
      std::snprintf(source_kind, sizeof source_kind, "%s", g_titles[index].kind);
    }
    pthread_mutex_unlock(&g_lock);

    if (std::strcmp(source_kind, "dump") == 0) {
      char json_path[640];
      char sfo_path[640];
      std::snprintf(json_path, sizeof json_path, "%s/sce_sys/param.json", source);
      std::snprintf(sfo_path, sizeof sfo_path, "%s/sce_sys/param.sfo", source);
      if (::access(json_path, F_OK) != 0 && ::access(sfo_path, F_OK) != 0) {
        job_finish(false,
                   "That folder has no sce_sys metadata (param.json or param.sfo), so no packer can "
                   "turn it into a package. Point me at the game folder itself, not its parent.");
        return;
      }
    }
  }

  // A package the Mac already holds must not be packed a second time: ask
  // first, then go straight to the transfer when it is already there.
  long long known_size = -1;
  {
    char ready_url[256];
    std::snprintf(ready_url, sizeof ready_url, "http://%s/api/ready/%s", mac, id);
    char probe[256] = {0};
    if (http_call("GET", ready_url, nullptr, probe, sizeof probe) == 200) {
      if (std::strstr(probe, "\"simulated\":true")) {
        job_finish(false,
                   "Your Mac has no packer configured, so it built a placeholder instead of a package. "
                   "Add fpkg-cli, or a custom packer command, in Prospero Vault there, then try again.");
        return;
      }
      const char* at = std::strstr(probe, "\"size\"");
      const char* colon = at ? std::strchr(at, ':') : nullptr;
      if (colon) known_size = std::atoll(colon + 1);
      log_fmt("convert: %s is already packed on the Mac", id);
      job_set("package ready on your Mac", 96);
    }
  }

  if (known_size < 0) {
    char build_url[256];
    std::snprintf(build_url, sizeof build_url, "http://%s/api/build", mac);
    char body[160];
    // pull:true lets the Mac take the dump from this console when it has no copy
    // of its own. Without it a dump that lives only here is a dead end.
    std::snprintf(body, sizeof body, "{\"titleId\":\"%s\",\"pull\":true}", id);

    job_set("asking your Mac to pack", 3);
    log_fmt("convert: asking %s", mac);
    char response[512];
    const int status = http_call("POST", build_url, body, response, sizeof response);
    log_fmt("convert: build request answered %d", status);
    // 200 or 202: a pull that is still running answers 202 straight away rather
    // than holding this request open for however long the copy takes.
    if (status != 200 && status != 202) {
      // The Mac explains itself now (no console configured, unsafe path, pull
      // failed); that reason is more useful than any sentence written here.
      char note[320] = {0};
      if (!json_string(response, "error", note, sizeof note)) {
        json_string(response, "message", note, sizeof note);
      }
      if (status == -1 || status == -2) {
        job_finish(false, "Cannot reach your Mac. Is Prospero Vault running there?");
      } else if (note[0]) {
        job_finish(false, note);
      } else {
        job_finish(false, "The Mac refused the job. Is Prospero Vault running there?");
      }
      return;
    }

    char progress_url[256];
    std::snprintf(progress_url, sizeof progress_url, "http://%s/api/progress/%s", mac, id);

    bool ready = false;
    bool failed = false;
    int misses = 0;  // consecutive unanswered polls
    int odd_code = 0;  // last answer this loop could not use
    // A real dump can pack for an hour; stop only when the Mac fails or the user does.
    for (int attempt = 0; attempt < 3600 && !ready && !failed; attempt++) {
      if (cancel_requested()) {
        job_finish(false, "Cancelled");
        return;
      }
      char polled[1024] = {0};
      const int code = http_call("GET", progress_url, nullptr, polled, sizeof polled);
      if (code < 0) {
        // A long pack survives a dropped frame or two, but an hour of silence
        // behind a frozen bar is not something to leave a player staring at.
        if (++misses < 20) {
          ::usleep(1000 * 1000);
          continue;
        }
        job_finish(false,
                   "Lost contact with your Mac while it was packing. Try Convert again — the build there "
                   "may still finish.");
        return;
      }
      misses = 0;

      if (code == 404) {
        // The Mac restarted, or forgot the title. If the package is already
        // there, take it; otherwise say so now rather than in an hour.
        char ready_url[256];
        char packed[512] = {0};
        std::snprintf(ready_url, sizeof ready_url, "http://%s/api/ready/%s", mac, id);
        if (http_call("GET", ready_url, nullptr, packed, sizeof packed) == 200) {
          ready = true;
          break;
        }
        job_finish(false, "Your Mac no longer knows this job — it may have restarted. Try Convert again.");
        return;
      }

      if (code != 200 && code != 404 && code != odd_code) {
        // Silently spinning on an answer this loop cannot read would leave the
        // player watching a frozen bar for an hour. Say what came back.
        odd_code = code;
        log_fmt("convert: progress poll for %s answered %d", id, code);
      }

      if (code == 200) {
        char line[160] = {0};
        char note[320] = {0};
        json_string(polled, "line", line, sizeof line);
        json_string(polled, "message", note, sizeof note);
        int pct = json_int(polled, "pct", 0);
        if (pct < 3) pct = 3;
        job_set(line[0] ? line : "packing", pct > 95 ? 95 : pct);
        if (std::strstr(polled, "\"ready\":true")) {
          ready = true;
          break;
        }
        if (std::strstr(polled, "\"state\":\"error\"")) {
          job_finish(false, note[0] ? note : "The packer failed on your Mac.");
          failed = true;
          break;
        }
      }
      ::usleep(1000 * 1000);
    }

    if (!ready && !failed) {
      job_finish(false, "Still packing on your Mac. Check the app there, then rescan.");
      return;
    }
    if (failed) return;
    if (cancel_requested()) {
      job_finish(false, "Cancelled");
      return;
    }
  }

  // A build that used the simulated engine is a placeholder. Downloading it
  // would spend bandwidth on a file this console will refuse, and calling that
  // a success would be worse than the wasted bytes.
  {
    char ready_url[256];
    std::snprintf(ready_url, sizeof ready_url, "http://%s/api/ready/%s", mac, id);
    char probe[320] = {0};
    if (http_call("GET", ready_url, nullptr, probe, sizeof probe) == 200) {
      if (std::strstr(probe, "\"simulated\":true")) {
        job_finish(false,
                   "Your Mac has no packer configured, so it built a placeholder instead of a package. "
                   "Add fpkg-cli, or a custom packer command, in Prospero Vault there, then try again.");
        return;
      }
      // A build that started from a pull had no size when the job began, so
      // read it now: the space check below needs it before the transfer starts.
      if (known_size < 0) {
        const char* at = std::strstr(probe, "\"size\"");
        const char* colon = at ? std::strchr(at, ':') : nullptr;
        if (colon) known_size = std::atoll(colon + 1);
      }
    }
  }

  // Space is finite and the transfer is long: say no now rather than at 80%.
  if (known_size > 0) {
    const long long free_now = free_bytes();
    if (free_now >= 0 && known_size + (256LL * 1024 * 1024) > free_now) {
      char have[32];
      char want[32];
      human_size(have, sizeof have, free_now);
      human_size(want, sizeof want, known_size);
      char message[320];
      std::snprintf(message, sizeof message,
                    "Not enough space on this console: the package is %s and %s is free. Free some "
                    "space, then press Convert again.",
                    want, have);
      job_finish(false, message);
      return;
    }
  }

  job_set("receiving package", 96);
  char pkg_url[256];
  std::snprintf(pkg_url, sizeof pkg_url, "http://%s/api/pkg/%s", mac, id);
  char destination[640];
  std::snprintf(destination, sizeof destination, "%s/%s.pkg", kGames, id);

  // Land in a .part file first: a package only appears under its real name
  // once every byte is on disk, so nothing half-written is ever playable.
  char partial[672];
  std::snprintf(partial, sizeof partial, "%s.part", destination);

  char why[256] = {0};
  long long bytes = 0;
  const int transferred = download(pkg_url, partial, known_size, &bytes, why, sizeof why);
  if (transferred != 0) {
    // A dropped link keeps the .part so the next attempt resumes; a cancel, an
    // unreachable host or an empty answer leaves nothing worth keeping.
    const bool keep = transferred != -10 && transferred != -1 && transferred != -2 && bytes > 0;
    if (!keep) ::unlink(partial);
    char message[320];
    if (transferred == -10) {
      std::snprintf(message, sizeof message, "Cancelled");
    } else if (keep) {
      std::snprintf(message, sizeof message, "%s — convert again to continue from there.", why);
    } else {
      std::snprintf(message, sizeof message, "%s", why);
    }
    job_finish(false, message);
    return;
  }

  if (::rename(partial, destination) != 0) {
    ::unlink(partial);
    job_finish(false, "Package arrived but could not be put in place for playing");
    return;
  }

  scan_all();
  char pretty[32];
  human_size(pretty, sizeof pretty, bytes);
  char message[256];
  std::snprintf(message, sizeof message, "Package received · %s", pretty);
  job_finish(true, message);
}

