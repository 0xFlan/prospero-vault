[[maybe_unused]] bool write_file_at(const char* path, const void* data, std::size_t length, mode_t mode) {
  const int fd = ::open(path, O_WRONLY | O_CREAT | O_TRUNC, mode);
  if (fd < 0) return false;

  const char* cursor = static_cast<const char*>(data);
  std::size_t left = length;
  while (left > 0) {
    const ssize_t wrote = ::write(fd, cursor, left);
    if (wrote <= 0) {
      ::close(fd);
      return false;
    }
    cursor += wrote;
    left -= static_cast<std::size_t>(wrote);
  }
  ::close(fd);
  // The console starts an app only when its files are open to every user.
  ::chmod(path, mode);
  return true;
}

[[maybe_unused]] bool copy_file_to(const char* from, const char* to) {
  const int source = ::open(from, O_RDONLY);
  if (source < 0) return false;
  const int sink = ::open(to, O_WRONLY | O_CREAT | O_TRUNC, 0777);
  if (sink < 0) {
    ::close(source);
    return false;
  }

  char buffer[64 * 1024];
  bool ok = true;
  while (ok) {
    const ssize_t got = ::read(source, buffer, sizeof buffer);
    if (got < 0) {
      ok = false;
      break;
    }
    if (got == 0) break;
    ssize_t wrote = 0;
    while (wrote < got) {
      const ssize_t step = ::write(sink, buffer + wrote, static_cast<std::size_t>(got - wrote));
      if (step <= 0) {
        ok = false;
        break;
      }
      wrote += step;
    }
  }

  ::close(source);
  ::close(sink);
  if (ok) ::chmod(to, 0777);
  return ok;
}

/**
 * Whether ShadowMountPlus holds this title.
 *
 * 1 when it answers for the title, 0 when it answers but does not hold it, and
 * -1 when nothing is listening. Asking per title, not for the whole library:
 * that answer is far larger than one HTTP reply here can hold, and a truncated
 * list would read as "not registered" for a title near its end.
 */
int shadowmount_state(const char* id) {
  char body[96];
  std::snprintf(body, sizeof body, "{\"title_id\":\"%s\"}", id);
  char answer[3072] = {0};
  const int status = mount_post("/api/v1/games/info", body, answer, sizeof answer);
  if (status < 0) return -1;
  if (status != 200) return 0;
  // A 200 whose own envelope reports a failure is not a registration.
  if (!std::strstr(answer, "\"status\":0") && !std::strstr(answer, "\"status\": 0")) return 0;
  return std::strstr(answer, id) ? 1 : 0;
}

/** Depth-first delete of a folder tree. Symlinks are unlinked, never followed. */
bool remove_tree(const char* path) {
  DIR* dir = ::opendir(path);
  if (dir) {
    struct dirent* entry = nullptr;
    while ((entry = ::readdir(dir)) != nullptr) {
      if (std::strcmp(entry->d_name, ".") == 0 || std::strcmp(entry->d_name, "..") == 0) continue;
      char child[512];
      std::snprintf(child, sizeof child, "%s/%s", path, entry->d_name);
      struct stat info;
      if (::lstat(child, &info) == 0 && S_ISDIR(info.st_mode)) {
        remove_tree(child);
      } else {
        ::unlink(child);
      }
    }
    ::closedir(dir);
  }
  return ::rmdir(path) == 0;
}

/**
 * Puts Prospero Vault in the home screen's app row.
 *
 * Writes the folder ShadowMountPlus registers — the console's web-app shell as
 * `eboot.bin`, the interface's own icon, and metadata naming this console's
 * address as the deeplink — then asks the payload for a scan so the tile appears
 * at once instead of at its next pass.
 *
 * Written is not registered, so this does not stop at the write: it asks
 * ShadowMountPlus whether it holds the title before saying so.
 *
 * Returns 1 when it is registered, 2 when the folder is written but nothing has
 * registered it, 3 when the tile was deliberately left off, 0 on a host build,
 * and -1 when nothing could be written.
 */
/** A development FSELF starts with 0x1D3D154F; the console shell eboot does not. */
bool is_native_eboot(const char* path) {
  unsigned char magic[4] = {0};
  const int file = ::open(path, O_RDONLY);
  if (file < 0) return false;
  const ssize_t got = ::read(file, magic, sizeof magic);
  ::close(file);
  return got == 4 && magic[0] == 0x4f && magic[1] == 0x15 && magic[2] == 0x3d && magic[3] == 0x1d;
}

int ensure_home_app(bool force, char* message, std::size_t cap) {
#if PV_HAVE_SONY
  if (!force && ::access(kHomeAppOptOut, F_OK) == 0) {
    pthread_mutex_lock(&g_lock);
    g_home_app = kHomeAppRemoved;
    pthread_mutex_unlock(&g_lock);
    std::snprintf(message, cap, "Prospero Vault was removed from the home screen, so it stays off.");
    return 3;
  }
  if (force) ::unlink(kHomeAppOptOut);

  if (::mkdir(kHomeAppRoot, 0777) != 0 && errno != EEXIST) {
    std::snprintf(message, cap, "Could not create %s (%s).", kHomeAppRoot, std::strerror(errno));
    return -1;
  }
  if (::mkdir(kHomeAppDir, 0777) != 0 && errno != EEXIST) {
    std::snprintf(message, cap, "Could not create %s (%s).", kHomeAppDir, std::strerror(errno));
    return -1;
  }

  char sce_sys[320];
  std::snprintf(sce_sys, sizeof sce_sys, "%s/sce_sys", kHomeAppDir);
  ::mkdir(sce_sys, 0777);

  char param_path[384];
  std::snprintf(param_path, sizeof param_path, "%s/param.json", sce_sys);
  char icon_path[384];
  std::snprintf(icon_path, sizeof icon_path, "%s/icon0.png", sce_sys);
  char eboot_path[384];
  std::snprintf(eboot_path, sizeof eboot_path, "%s/eboot.bin", kHomeAppDir);

  // The native title writes this folder from its installer. Rewriting the
  // web-app metadata here would point the tile at a browser page and drop the
  // native app's own manifest, so an installed native eboot is left alone.
  if (is_native_eboot(eboot_path)) {
    pthread_mutex_lock(&g_lock);
    g_home_app = kHomeAppRegistered;
    pthread_mutex_unlock(&g_lock);
    std::snprintf(message, cap,
                  "The native Prospero Vault title is installed, so the web-app tile fallback was left "
                  "alone. Launch Prospero Vault from the app row.");
    return 1;
  }

  // The console's own shell metadata: what the home screen reads to draw the
  // tile, and the address the web-app shell opens when it is pressed. The
  // attribute fields are the ones the console's own registered web app carries
  // (websrv's loader writes them for its fake app), so this mirrors a metadata
  // file the shell is known to accept instead of inventing a shape.
  char json[1024];
  const int length = std::snprintf(
    json, sizeof json,
    "{\n"
    "  \"applicationCategoryType\": 0,\n"
    "  \"attribute\": 1,\n"
    "  \"attribute2\": 0,\n"
    "  \"attribute3\": 4,\n"
    "  \"contentId\": \"%s\",\n"
    "  \"titleId\": \"%s\",\n"
    "  \"deeplinkUri\": \"http://127.0.0.1:%d/\",\n"
    "  \"localizedParameters\": {\n"
    "    \"defaultLanguage\": \"en-US\",\n"
    "    \"en-US\": { \"titleName\": \"%s\" }\n"
    "  }\n"
    "}\n",
    kHomeAppContentId, kHomeAppId, g_port, kHomeAppTitle);
  if (length <= 0 || static_cast<std::size_t>(length) >= sizeof json) {
    std::snprintf(message, cap, "Could not compose the tile's metadata.");
    return -1;
  }
  if (!write_file_at(param_path, json, static_cast<std::size_t>(length), 0777)) {
    std::snprintf(message, cap, "Could not write %s (%s).", param_path, std::strerror(errno));
    return -1;
  }

  // The icon is embedded, so the tile is drawn by the app itself and there is no
  // second file to keep in step.
  if (!write_file_at(icon_path, kIconPng, kIconPngLen, 0777)) {
    log_fmt("home app: icon not written (%s)", std::strerror(errno));
  }

  // A shell path can differ by firmware, so it can be named in config.json as
  // "shellEboot" instead of being recompiled.
  const char* shell = kShellEboot;
  char body[1024];
  char configured[256] = {0};
  if (read_small_file(kConfigFile, body, sizeof body) &&
      json_string(body, "shellEboot", configured, sizeof configured) && configured[0]) {
    shell = configured;
  }

  bool startable = ::access(eboot_path, X_OK) == 0;
  if (!startable && ::access(shell, R_OK) == 0) {
    startable = copy_file_to(shell, eboot_path);
    log_fmt("home app: eboot from %s -> %s", shell, startable ? "ok" : "failed");
  }

  if (!startable) {
    pthread_mutex_lock(&g_lock);
    g_home_app = kHomeAppPending;
    pthread_mutex_unlock(&g_lock);
    std::snprintf(message, cap,
                  "The tile is written, but this console has no web-app shell at %s, so it would not "
                  "start. Name one as \"shellEboot\" in config.json, then add it again.",
                  shell);
    return 2;
  }

  // A folder on disk is not a tile. Only ShadowMountPlus can hand it to the
  // shell, so ask it for a pass and then ask whether it really holds the title
  // before reporting anything as installed.
  char answer[256] = {0};
  const int scan = mount_post("/api/v1/scan", "{\"reset_attempts\":true}", answer, sizeof answer);
  log_fmt("home app: %s, scan -> %d", kHomeAppDir, scan);

  int registered = -1;
  for (int attempt = 0; attempt < 8; attempt++) {
    registered = shadowmount_state(kHomeAppId);
    if (registered != 0) break;  // 1 held, -1 nobody to ask
    ::usleep(400 * 1000);
  }

  pthread_mutex_lock(&g_lock);
  g_home_app = registered == 1 ? kHomeAppRegistered : kHomeAppPending;
  pthread_mutex_unlock(&g_lock);
  log_fmt("home app: registered=%d", registered);

  if (registered == 1) {
    std::snprintf(message, cap,
                  "Prospero Vault is registered with ShadowMountPlus and is in the app row. Its tile "
                  "opens this interface full screen.");
    return 1;
  }

  if (registered < 0) {
    std::snprintf(message, cap,
                  "The tile folder is written, but nothing answers on 127.0.0.1:10101, so "
                  "ShadowMountPlus has not registered it. Start ShadowMountPlus, then add it again.");
    return 2;
  }

  std::snprintf(message, cap,
                "The folder is written, but ShadowMountPlus still does not list PVLT00001. Check that its "
                "scan paths include /data/homebrew, then add it again.");
  return 2;
#else
  (void)force;
  std::snprintf(message, cap,
                "The home screen app is written on the console: a host build has no /data/homebrew to "
                "register it in.");
  return 0;
#endif
}

/**
 * Takes the tile back off the home screen.
 *
 * The folder is the registration, so it goes first, then the title is
 * uninstalled and a scan requested: ShadowMountPlus drops a registration whose
 * source is gone, and a successful uninstall of an absent source queues the
 * synchronisation that does it. Uninstalling first would be refused with EBUSY,
 * because the title asking is the title running.
 *
 * Returns 1 when the tile is gone, 2 when the folder went but the payload still
 * lists it, and -1 when the folder could not be deleted.
 */
int remove_home_app(char* message, std::size_t cap) {
#if PV_HAVE_SONY
  char native_eboot[384];
  std::snprintf(native_eboot, sizeof native_eboot, "%s/eboot.bin", kHomeAppDir);
  if (is_native_eboot(native_eboot)) {
    std::snprintf(message, cap,
                  "The native Prospero Vault title is installed. Removing this folder would delete the "
                  "app itself, so it was left in place. Close the app and remove %s with a file manager "
                  "only if you mean to uninstall it.",
                  kHomeAppDir);
    return 2;
  }

  const bool gone = remove_tree(kHomeAppDir) || ::access(kHomeAppDir, F_OK) != 0;
  // Remember the decision only once the tile really went, or the next payload
  // start would leave a half-removed tile that never comes back.
  if (gone) write_file_at(kHomeAppOptOut, "removed\n", 8, 0777);

  char body[96];
  std::snprintf(body, sizeof body, "{\"title_id\":\"%s\"}", kHomeAppId);
  char answer[1024] = {0};
  const int uninstall = mount_post("/api/v1/games/uninstall", body, answer, sizeof answer);
  mount_post("/api/v1/scan", "{\"reset_attempts\":true}", answer, sizeof answer);
  log_fmt("home app: remove -> folder %s, uninstall %d", gone ? "gone" : "kept", uninstall);

  int registered = -1;
  for (int attempt = 0; attempt < 8; attempt++) {
    registered = shadowmount_state(kHomeAppId);
    if (registered == 0) break;
    ::usleep(400 * 1000);
  }

  pthread_mutex_lock(&g_lock);
  g_home_app = gone && registered == 0 ? kHomeAppRemoved : kHomeAppPending;
  pthread_mutex_unlock(&g_lock);

  if (!gone) {
    std::snprintf(message, cap, "Could not delete %s (%s). Nothing was changed.", kHomeAppDir,
                  std::strerror(errno));
    return -1;
  }
  if (registered != 0) {
    std::snprintf(message, cap,
                  "The folder is gone, but ShadowMountPlus still lists PVLT00001. Uninstall it there, or "
                  "rescan, and the tile will go.");
    return 2;
  }

  std::snprintf(message, cap,
                "Removed from the home screen. This window keeps running until you close it, and the app "
                "will not put itself back.");
  return 1;
#else
  std::snprintf(message, cap,
                "The home screen app lives on the console: a host build has none to remove.");
  return 0;
#endif
}

/**
 * Starts a title. Packages ask the mount payload for the fake-library policy a
 * debug FPKG needs; images ask it to mount. Then Sony's own launcher runs the
 * title. Nothing is cached, copied or rebuilt, so the cost is one call.
 */
PlayResult play_title(const char* id, const char* kind) {
  PlayResult result;
  std::memset(&result, 0, sizeof result);

  // An image has to be mounted before any launcher call makes sense, and whether
  // anything is listening is a fact on every build — so it is answered before
  // the console-only path rather than buried inside it.
  if (std::strcmp(kind, "image") == 0 && !mount_payload_ready(false)) {
    result.unsupported = true;
    result.code = 501;
    std::snprintf(result.message, sizeof result.message,
                  "A disc image has to be mounted before it can start, and nothing is listening on "
                  "127.0.0.1:10101 to mount it. Convert it to a package on your Mac and it installs "
                  "like any other game on this console.");
    return result;
  }

#if PV_HAVE_SONY
  // An installed package is mounted by the console itself: it lives in
  // /user/app like any other game, and the shell's own launcher attaches it.
  // Asking a third-party payload to fake a library first would replace the
  // normal path with a different one, so it is never done for a package.
  if (std::strcmp(kind, "image") == 0) {
    char body[192];
    char answer[512] = {0};
    std::snprintf(body, sizeof body, "{\"title_id\":\"%s\",\"mode\":\"ro\"}", id);
    log_fmt("play: mount %s -> %d", id, mount_post("/api/v1/games/mount", body, answer, sizeof answer));
  }

  static pthread_mutex_t launch_lock = PTHREAD_MUTEX_INITIALIZER;
  pthread_mutex_lock(&launch_lock);

  sceUserServiceInitialize(nullptr);
  int user = 0;
  const int user_rc = sceUserServiceGetForegroundUser(&user);
  if (user_rc != 0 || user <= 0) {
    result.code = user_rc;
    std::snprintf(result.message, sizeof result.message,
                  "No profile is signed in, so the launcher has nobody to start %s as.", id);
    pthread_mutex_unlock(&launch_lock);
    return result;
  }

  sceLncUtilInitialize();

  if (pv_game_running(id)) {
    // Exactly one request: a second one backgrounds the game that is already up.
    sceSystemServiceLaunchApp(id, nullptr, nullptr);
    result.ok = true;
    std::snprintf(result.message, sizeof result.message, "%s is already running, so it was brought to the front.", id);
    pthread_mutex_unlock(&launch_lock);
    return result;
  }

  struct LncParam {
    std::uint32_t size;
    std::int32_t user;
    std::uint32_t options;
    std::uint64_t crash_report;
    std::uint64_t check_flag;
  } __attribute__((packed)) param;
  std::memset(&param, 0, sizeof param);
  param.size = sizeof param;
  param.user = user;

  int rc = sceLncUtilLaunchApp(id, nullptr, &param);
  bool started = rc == 0;
  if (!started) {
    // Some firmwares reject a parameter block but accept a bare call.
    rc = sceLncUtilLaunchApp(id, nullptr, nullptr);
    started = rc == 0;
  }
  if (!started) {
    // This one returns the new app id on success, so only a negative value is
    // a failure. Reading it as "must be zero" would fire a second launch.
    const int sys = sceSystemServiceLaunchApp(id, nullptr, nullptr);
    started = sys >= 0;
    if (!started) rc = sys;
  }
  if (!started) {
    for (int i = 0; i < 12 && !started; i++) {
      ::usleep(250 * 1000);
      started = pv_game_running(id);
    }
  }

  if (started) {
    pthread_mutex_lock(&g_lock);
    g_playing = true;
    std::snprintf(g_play_id, sizeof g_play_id, "%s", id);
    rebuild_json_locked();
    pthread_mutex_unlock(&g_lock);

    // Give the game its memory back. The icon cache is the payload's largest
    // allocation, and nothing reads icons while a title runs; they come back
    // on demand afterwards.
    icon_clear();
    result.ok = true;
    std::snprintf(result.message, sizeof result.message, "Launched %s.", id);
  } else {
    result.code = rc;
    std::snprintf(result.message, sizeof result.message,
                  "The console refused the launch (0x%08x). A package has to be installed before it can start.",
                  static_cast<unsigned>(rc));
  }

  pthread_mutex_unlock(&launch_lock);
#else
  (void)id;
  (void)kind;
  result.unsupported = true;
  std::snprintf(result.message, sizeof result.message,
                "Play is built for the console: this host build cannot start a title.");
#endif
  return result;
}

#if PV_HAVE_SONY
/** Clears the playing flag when the title exits, so scans can resume. */
void* play_watchdog(void*) {
  while (true) {
    // Ten seconds: one wakeup per ten, and still well inside the time it takes
    // someone to notice a game closed and press Rescan.
    ::usleep(10 * 1000 * 1000);

    char id[16];
    pthread_mutex_lock(&g_lock);
    const bool playing = g_playing;
    std::snprintf(id, sizeof id, "%s", g_play_id);
    pthread_mutex_unlock(&g_lock);
    if (!playing || !id[0] || pv_game_running(id)) continue;

    pthread_mutex_lock(&g_lock);
    g_playing = false;
    g_play_id[0] = '\0';
    rebuild_json_locked();
    pthread_mutex_unlock(&g_lock);
    log_fmt("play: %s exited", id);
  }
  return nullptr;
}
#endif

