/** False means the write failed: a full disk, not a slow client. */
bool write_all(int fd, const void* data, std::size_t length) {
  const char* text = static_cast<const char*>(data);
  while (length > 0) {
    const ssize_t written = ::write(fd, text, length);
    if (written < 0) {
      if (errno == EINTR) continue;
      return false;
    }
    if (written == 0) return false;
    text += written;
    length -= static_cast<std::size_t>(written);
  }
  return true;
}

void log_line(const char* text) {
  char buffer[512];
  const int length = std::snprintf(buffer, sizeof buffer, "%s\n", text);
  if (length <= 0) return;
  const std::size_t size = static_cast<std::size_t>(length) < sizeof buffer
                               ? static_cast<std::size_t>(length)
                               : sizeof buffer - 1;
  pthread_mutex_lock(&g_log_lock);
  write_all(STDOUT_FILENO, buffer, size);
  if (g_log_fd >= 0) write_all(g_log_fd, buffer, size);
  pthread_mutex_unlock(&g_log_lock);
}

void log_fmt(const char* fmt, ...) {
  char buffer[512];
  va_list args;
  va_start(args, fmt);
  std::vsnprintf(buffer, sizeof buffer, fmt, args);
  va_end(args);
  log_line(buffer);
}

