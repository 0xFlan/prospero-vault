unsigned read16(const unsigned char* p) { return static_cast<unsigned>(p[0]) | (static_cast<unsigned>(p[1]) << 8); }
unsigned read32(const unsigned char* p) {
  return static_cast<unsigned>(p[0]) | (static_cast<unsigned>(p[1]) << 8) |
         (static_cast<unsigned>(p[2]) << 16) | (static_cast<unsigned>(p[3]) << 24);
}

void copy_field(char* out, std::size_t cap, const unsigned char* data, std::size_t length) {
  if (!cap) return;
  std::size_t n = length < cap - 1 ? length : cap - 1;
  while (n > 0 && data[n - 1] == 0) n--;
  std::memcpy(out, data, n);
  out[n] = '\0';
  trim_utf8(out, n);
}

bool sfo_read(const char* path, char* title, std::size_t title_cap, char* id, std::size_t id_cap) {
  static unsigned char buffer[65536];
  const int fd = ::open(path, O_RDONLY);
  if (fd < 0) return false;
  const ssize_t bytes = ::read(fd, buffer, sizeof buffer);
  ::close(fd);
  if (bytes < 20) return false;
  if (read32(buffer) != 0x46535000u) return false;

  const std::size_t size = static_cast<std::size_t>(bytes);
  const unsigned key_table = read32(buffer + 8);
  const unsigned data_table = read32(buffer + 12);
  const unsigned count = read32(buffer + 16);

  for (unsigned i = 0; i < count; i++) {
    const std::size_t entry = 20 + static_cast<std::size_t>(i) * 16;
    if (entry + 16 > size) break;

    const unsigned key_offset = read16(buffer + entry);
    const unsigned format = read16(buffer + entry + 2);
    const unsigned length = read32(buffer + entry + 4);
    const unsigned data_offset = read32(buffer + entry + 12);
    if (format == 0x0404) continue;  // integers

    const std::size_t key_start = key_table + key_offset;
    if (key_start >= size) continue;
    const char* key = reinterpret_cast<const char*>(buffer + key_start);
    const std::size_t key_length = ::strnlen(key, size - key_start);

    const std::size_t data_start = data_table + data_offset;
    if (data_start >= size) continue;
    const std::size_t available = size - data_start;
    const std::size_t copy = length < available ? length : available;

    if (key_length == 5 && std::memcmp(key, "TITLE\0", 6) == 0) {
      copy_field(title, title_cap, buffer + data_start, copy);
    } else if (key_length == 8 && std::memcmp(key, "TITLE_ID", 9) == 0) {
      copy_field(id, id_cap, buffer + data_start, copy);
    }
  }
  return true;
}

