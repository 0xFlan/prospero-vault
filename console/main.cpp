/** 13.20 -> 1320; anything that is not a version is 0 (unknown). */
int parse_firmware_code(const char* text) {
  int major = 0;
  int minor = 0;
  if (!text || std::sscanf(text, "%d.%d", &major, &minor) != 2) return 0;
  if (major <= 0 || minor < 0) return 0;
  return major * 100 + minor;
}

/**
 * Reads the console's firmware for the capability report.
 *
 * sceKernelGetProsperoSystemSwVersion is the direct answer. uname is kept as a
 * fallback because a payload that replaces or hides libkernel's answer should
 * still be able to say "unknown" rather than crashing.
 */
void read_firmware_version() {
#if PV_HAVE_SONY
  char text[40] = {0};
  SceSystemSwVersion version;
  std::memset(&version, 0, sizeof version);
  const int rc = sceKernelGetProsperoSystemSwVersion(&version);
  if (rc == 0 && version.bin_version) {
    std::snprintf(text, sizeof text, "%x.%02x",
                  static_cast<unsigned>((version.bin_version >> 24) & 0xffu),
                  static_cast<unsigned>((version.bin_version >> 16) & 0xffu));
  }
  if (!text[0] && rc == 0 && version.str_version[0]) {
    std::snprintf(text, sizeof text, "%.*s", static_cast<int>(sizeof version.str_version), version.str_version);
  }
  if (!text[0]) {
    struct utsname system_name;
    if (::uname(&system_name) == 0) std::snprintf(text, sizeof text, "%s", system_name.release);
  }
  if (text[0]) {
    std::size_t length = std::strlen(text);
    while (length > 0 && (text[length - 1] == ' ' || text[length - 1] == '\t')) text[--length] = '\0';
    std::snprintf(g_firmware, sizeof g_firmware, "%s", text);
    g_firmware_code = parse_firmware_code(text);
  }
  if (g_firmware_code > 0) {
    log_fmt("firmware: %s", g_firmware);
  } else {
    log_fmt("firmware: %s (install support unknown)", g_firmware);
  }
#else
  std::snprintf(g_firmware, sizeof g_firmware, "host");
  g_firmware_code = 0;
#endif
}

/**
 * What the public tooling supports on this firmware, not what a hopeful UI would
 * like. The install ceiling is a property of kstuff/ppr-patch, not of Vault.
 */
void install_capability(char* state, std::size_t state_cap, char* reason, std::size_t reason_cap) {
#if PV_HAVE_SONY
  if (g_firmware_code <= 0) {
    std::snprintf(state, state_cap, "unknown");
    std::snprintf(reason, reason_cap,
                  "This payload could not read the firmware version, so install support is unknown. "
                  "The console's installer reports the real result.");
  } else if (g_firmware_code <= 1160) {
    std::snprintf(state, state_cap, "supported");
    std::snprintf(reason, reason_cap,
                  "This firmware is inside the public kstuff/ppr-patch install range (through 11.60). "
                  "That is the documented ceiling, not a test on this machine.");
  } else if (g_firmware_code <= 1360) {
    std::snprintf(state, state_cap, "blocked");
    std::snprintf(reason, reason_cap,
                  "Public kstuff/ppr-patch support for debug-package installs stops at 11.60. On %s the "
                  "console's installer returns 0x80BD0005, so mount the dump or image instead.",
                  g_firmware);
  } else {
    std::snprintf(state, state_cap, "unavailable");
    std::snprintf(reason, reason_cap,
                  "There is no public exploit above 13.60, so this payload cannot run there and no "
                  "debug-package install path exists.");
  }
#else
  std::snprintf(state, state_cap, "host");
  std::snprintf(reason, reason_cap, "A host build cannot install a package.");
#endif
}

bool ends_with(const char* text, const char* suffix) {
  const std::size_t a = std::strlen(text);
  const std::size_t b = std::strlen(suffix);
  return a >= b && std::strcmp(text + a - b, suffix) == 0;
}

bool is_title_id(const char* text) {
  if (std::strlen(text) != 9) return false;
  for (int i = 0; i < 9; i++) {
    const char c = text[i];
    if (i < 4 ? (c < 'A' || c > 'Z') : (c < '0' || c > '9')) return false;
  }
  return true;
}

/**
 * Pulls the title id out of a package filename.
 *
 * A debug package is normally named after its content id, for example
 * `UP9000-PTST00001_00-SAMPLE...pkg` or
 * `ddadcba1e9326627-JP0700-PPSA24913_00-MAINGAME...pkg`. The 16-character
 * prefix the old scanner kept is neither id: it made an installed package look
 * uninstalled and sent launch at a title the console never registered. The id
 * is the nine-character segment between dashes, before the `_00` suffix.
 */
void package_title_id(const char* filename, char* out, std::size_t cap) {
  if (cap) out[0] = '\0';
  const char* at = filename;
  while (*at) {
    const char* dash = std::strchr(at, '-');
    const char* end = dash ? dash : at + std::strlen(at);
    const char* underscore = static_cast<const char*>(std::memchr(at, '_', static_cast<std::size_t>(end - at)));
    const std::size_t length = static_cast<std::size_t>((underscore ? underscore : end) - at);
    if (length == 9 && length + 1 < cap) {
      char candidate[10];
      std::memcpy(candidate, at, length);
      candidate[length] = '\0';
      if (is_title_id(candidate)) {
        std::snprintf(out, cap, "%s", candidate);
        return;
      }
    }
    if (!dash) break;
    at = dash + 1;
  }
}

/**
 * The image formats a mount payload can attach. They carry no readable
 * filesystem here, so the filename is the only metadata until it is mounted.
 */
/**
 * A stable 9-character id for a source whose folder name is not a title id —
 * one DLC folder per content id, or a dump named after the game. Nine because
 * every /api/dump/<id> route reads exactly that many characters.
 */
void source_id(const char* key, char* out, std::size_t cap) {
  unsigned long long hash = 1469598103934665603ull;
  for (const char* p = key; *p; p++) {
    hash ^= static_cast<unsigned char>(*p);
    hash *= 1099511628211ull;
  }
  std::snprintf(out, cap, "pv%07llx", hash & 0xfffffffull);
}

bool is_image_file(const char* name) {
  static const char* const kSuffixes[] = {".exfat", ".ffpkg", ".ffpfs", ".ffpfsc"};
  for (const char* suffix : kSuffixes) {
    if (ends_with(name, suffix)) return true;
  }
  return false;
}

/** "host" or "host:port" only: anything else could smuggle CRLF into a request. */
bool valid_host(const char* text) {
  const std::size_t length = std::strlen(text);
  if (length == 0 || length >= 64) return false;
  int colons = 0;
  for (std::size_t i = 0; i < length; i++) {
    const char c = text[i];
    if (c == ':') {
      if (++colons > 1) return false;
      continue;
    }
    const bool allowed = (c >= '0' && c <= '9') || (c >= 'a' && c <= 'z') ||
                         (c >= 'A' && c <= 'Z') || c == '.' || c == '-';
    if (!allowed) return false;
  }
  return true;
}

/** A stalled client must not be able to wedge a worker thread. */
void set_timeouts(int fd, int recv_seconds, int send_seconds) {
  struct timeval tv;
  tv.tv_sec = recv_seconds;
  tv.tv_usec = 0;
  ::setsockopt(fd, SOL_SOCKET, SO_RCVTIMEO, &tv, sizeof tv);
  tv.tv_sec = send_seconds;
  ::setsockopt(fd, SOL_SOCKET, SO_SNDTIMEO, &tv, sizeof tv);
}

bool cancel_requested() {
  pthread_mutex_lock(&g_lock);
  const bool value = g_cancel;
  pthread_mutex_unlock(&g_lock);
  return value;
}

void human_size(char* out, std::size_t cap, long long bytes) {
  static const char* units[] = {"B", "KB", "MB", "GB", "TB"};
  double value = static_cast<double>(bytes);
  int unit = 0;
  while (value >= 1024.0 && unit < 4) {
    value /= 1024.0;
    unit++;
  }
  if (unit == 0) {
    std::snprintf(out, cap, "%lld %s", bytes, units[unit]);
  } else {
    std::snprintf(out, cap, "%.1f %s", value, units[unit]);
  }
}

/** Truncation can split a UTF-8 sequence, which would make the JSON unparseable. */
void trim_utf8(char* text, std::size_t length) {
  std::size_t cut = length;
  while (cut > 0 && (static_cast<unsigned char>(text[cut - 1]) & 0xC0) == 0x80) cut--;
  if (cut == 0) {
    text[0] = '\0';
    return;
  }
  const unsigned char lead = static_cast<unsigned char>(text[cut - 1]);
  std::size_t need = 1;
  if (lead >= 0xF0) need = 4;
  else if (lead >= 0xE0) need = 3;
  else if (lead >= 0xC0) need = 2;
  if (cut - 1 + need > length) text[cut - 1] = '\0';
}

