/**
 * One probe, remembered: the mount payload is either there or it is not.
 * force re-asks, which the scan does so a payload started later is noticed.
 */
bool mount_payload_ready(bool force) {
  pthread_mutex_lock(&g_lock);
  const int known = g_mount_payload;
  pthread_mutex_unlock(&g_lock);
  if (known && !force) return known == 1;

  char url[128];
  char answer[512] = {0};
  std::snprintf(url, sizeof url, "%s/api/v1/version", kMountBase);
  const int status = http_call("POST", url, "{}", answer, sizeof answer);
  const bool here = status == 200 && std::strstr(answer, "\"api_version\"") != nullptr;

  pthread_mutex_lock(&g_lock);
  const bool changed = known != (here ? 1 : 2);
  g_mount_payload = here ? 1 : 2;
  pthread_mutex_unlock(&g_lock);
  if (changed) log_fmt("mount payload on 10101: %s", here ? "found" : "not found");
  return here;
}

