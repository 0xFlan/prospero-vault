/**
 * Installs a local .pkg through the console's local installer service, then
 * optionally starts it.
 *
 * The service is the same one the web file manager drives. It is asked over
 * loopback with a form body, because libSceAppInstUtil cannot be mapped into
 * this process on 13.20. An install is accepted asynchronously; completion is
 * read from /user/app rather than guessed, and a missing service is reported
 * as such instead of pretending the package was handed over.
 */
bool install_package(const char* id, bool launch_after, char* message, std::size_t cap) {
#if PV_HAVE_SONY
  char path[512] = {0};
  pthread_mutex_lock(&g_lock);
  const int index = find_title_locked(id);
  if (index >= 0) std::snprintf(path, sizeof path, "%s", g_titles[index].path);
  pthread_mutex_unlock(&g_lock);

  if (!path[0]) {
    std::snprintf(message, cap, "%s is no longer in the library. Rescan, then try again.", id);
    return false;
  }

  if (!title_installed(id)) {
    job_set("handing the package to this console", 12);
    log_fmt("install: %s -> %s", id, path);

    char encoded[1600];
    url_encode(encoded, sizeof encoded, path);
    char form[1664];
    std::snprintf(form, sizeof form, "paths=%s", encoded);
    char answer[512] = {0};
    const int status = http_call_ex("POST", "http://127.0.0.1:8888/api/install-pkg", form,
                                    "application/x-www-form-urlencoded", answer, sizeof answer);
    if (status < 0) {
      std::snprintf(message, cap,
                    "No local installer service is answering on port 8888, so %s cannot be handed to "
                    "the console. Start the console's file manager payload, then press Install again.",
                    id);
      return false;
    }
    if (status != 200 || std::strstr(answer, "\"ok\":true") == nullptr) {
      std::snprintf(message, cap,
                    "The local installer service refused %s (HTTP %d). The file manager's log has the "
                    "reason; a package built for another firmware is turned down this way.",
                    id, status);
      return false;
    }

    // Thirty minutes: a large package on a slow drive really is slow, and
    // waiting is better than telling someone their install failed.
    bool done = title_installed(id);
    int tick = 0;
    while (!done && tick < 900) {
      if (cancel_requested()) {
        std::snprintf(message, cap, "Stopped waiting. The console may still be installing %s.", id);
        return false;
      }
      const int pct = 15 + tick / 2;  // 15% -> 95% across about four minutes
      job_set("installing on this console", pct > 95 ? 95 : pct);
      ::usleep(2000 * 1000);
      tick++;
      done = title_installed(id);
    }
    if (!done) {
      std::snprintf(message, cap,
                    "%s is still installing. The console reports it when it is ready — watch its "
                    "notifications, then press Play.",
                    id);
      return false;
    }
  }

  pthread_mutex_lock(&g_lock);
  const int at = find_title_locked(id);
  if (at >= 0) g_titles[at].installed = true;
  rebuild_json_locked();
  pthread_mutex_unlock(&g_lock);

  if (launch_after) {
    const PlayResult played = play_title(id, "pkg");
    std::snprintf(message, cap, "%s", played.message);
    return played.ok;
  }

  // Installing through the console's own installer is also what gives the game
  // its own tile: the shell registers it in the games row, where it starts like
  // any other game, with or without this app.
  std::snprintf(message, cap,
                "Installed. The console put it in its own games row, so it starts from the home screen "
                "like any other game.");
  return true;
#else
  (void)id;
  (void)launch_after;
  std::snprintf(message, cap, "Install is built for the console: this host build cannot install a package.");
  return false;
#endif
}

struct InstallArgs {
  char id[16];
  bool launch;
};

void* install_thread(void* raw) {
  const InstallArgs args = *static_cast<InstallArgs*>(raw);
  std::free(raw);

  char message[320] = {0};
  const bool ok = install_package(args.id, args.launch, message, sizeof message);
  job_finish(ok, message);
  return nullptr;
}

enum StartResult { kStarted = 0, kBusy = 1, kFailed = 2 };

/**
 * Claims the single background task slot and starts an installer. Two jobs at
 * once would fight for the same disk and Wi-Fi, and one of them would be a lie.
 */
int start_install(const char* id, bool launch) {
  pthread_mutex_lock(&g_lock);
  const bool busy = g_job.active;
  if (!busy) {
    g_job.active = true;
    g_job.done = false;
    g_job.ok = false;
    g_job.pct = 2;
    g_cancel = false;
    std::snprintf(g_job.kind, sizeof g_job.kind, "install");
    std::snprintf(g_job.id, sizeof g_job.id, "%s", id);
    std::snprintf(g_job.line, sizeof g_job.line, "starting");
    g_job.message[0] = '\0';
  }
  pthread_mutex_unlock(&g_lock);
  if (busy) return kBusy;

  InstallArgs* args = static_cast<InstallArgs*>(std::malloc(sizeof(InstallArgs)));
  if (!args) {
    pthread_mutex_lock(&g_lock);
    g_job.active = false;
    pthread_mutex_unlock(&g_lock);
    return kFailed;
  }
  std::memset(args, 0, sizeof(InstallArgs));
  std::snprintf(args->id, sizeof args->id, "%s", id);
  args->launch = launch;

  pthread_t thread;
  if (::pthread_create(&thread, nullptr, install_thread, args) != 0) {
    std::free(args);
    pthread_mutex_lock(&g_lock);
    g_job.active = false;
    pthread_mutex_unlock(&g_lock);
    return kFailed;
  }
  ::pthread_detach(thread);
  return kStarted;
}

